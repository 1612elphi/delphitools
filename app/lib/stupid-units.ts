export interface StupidUnit {
	key: string;
	name: string;
	factor: number;
}

export interface StupidCategory {
	key: string;
	name: string;
	symbol: string;
	units: StupidUnit[];
}

type Row = [name: string, factor: number];

const slug = (name: string) =>
	name
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-|-$/g, '');

function category(
	key: string,
	name: string,
	symbol: string,
	rows: Row[],
): StupidCategory {
	return {
		key,
		name,
		symbol,
		units: rows
			.map(([unitName, factor]) => ({
				key: slug(unitName),
				name: unitName,
				factor,
			}))
			.sort((a, b) => a.factor - b.factor),
	};
}

